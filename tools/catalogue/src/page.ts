// The catalogue as one self-contained HTML file: the screenshots are inlined
// as data URLs, so the page works opened from disk or hosted anywhere.

import type { CatalogueApp, CatalogueScene } from './catalogue.ts';

export interface PageOptions {
  readonly apps: readonly CatalogueApp[];
  /** The stylesheet, inlined. */
  readonly style: string;
  /** The firmware commit the emulator drew with. */
  readonly firmwareCommit: string;
  /** From the page to the workspace root, for links to the READMEs. */
  readonly rootHref: string;
}

/** What every app has in common, before the apps themselves. */
const ANATOMY = [
  [
    'Fetch',
    'Apps that need outside data poll it in the background and keep the latest value, so a slow source never stalls a frame.',
  ],
  [
    'Render',
    'A pure function maps the current time and that value to display elements: text, rectangles, images.',
  ],
  [
    'Draw',
    'The frame loop sends the elements to the bar over its HTTP API, about once a second, and deletes the ones a frame stops drawing.',
  ],
  [
    'Show',
    'The bar lays them out with its firmware fonts on the 72×16 RGB front and the 160×80 grey back screen.',
  ],
] as const;

export function cataloguePage({
  apps,
  style,
  firmwareCommit,
  rootHref,
}: PageOptions): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>BUSY Bar apps</title>
<style>
${style}</style>
</head>
<body>
<header class="hero">
<p class="eyebrow">Catalogue</p>
<h1>BUSY Bar apps</h1>
<p class="lede">${apps.length} small programs that run on a computer and draw on the BUSY Bar through its HTTP API. Every display below is drawn by the app’s own render function from sample data, then rendered by the emulator the way the bar renders it.</p>
<nav class="index" aria-label="Apps">
${apps.map(indexEntry).join('\n')}
</nav>
</header>
<section class="anatomy" aria-labelledby="anatomy">
<h2 id="anatomy">How every app works</h2>
<ol class="pipeline">
${ANATOMY.map(([label, text]) => `<li><b>${label}</b><span>${text}</span></li>`).join('\n')}
</ol>
</section>
<main>
${apps.map((app) => appSection(app, rootHref)).join('\n')}
</main>
<footer>
<p>Generated by <code>NX_DAEMON=false yarn nx run catalogue:build</code> from each app’s <code>preview</code> target. Drawn with firmware <code>${escape(firmwareCommit.slice(0, 7))}</code>.</p>
</footer>
</body>
</html>
`;
}

function indexEntry({ project, summary }: CatalogueApp): string {
  return `<a href="#${escape(project.name)}"><code>${escape(project.name)}</code><span>${escape(summary)}</span></a>`;
}

function appSection(app: CatalogueApp, rootHref: string): string {
  const { project } = app;
  const name = escape(project.name);
  return `<article class="app" id="${name}" aria-labelledby="${name}-title">
<header>
<h2 id="${name}-title"><code>${name}</code></h2>
<span class="language" data-language="${escape(project.language)}">${escape(project.language)}</span>
</header>
<p class="summary">${escape(app.summary)}</p>
<div class="scenes">
${app.scenes.map((scene) => sceneFigure(project.name, scene)).join('\n')}
</div>
<div class="details">
<section class="how">
<h3>How it works</h3>
<dl>
${app.steps.map((step) => `<div><dt>${escape(step.label)}</dt><dd>${escape(step.text)}</dd></div>`).join('\n')}
</dl>
</section>
<section class="run">
<h3>Run it</h3>
<pre><code>NX_DAEMON=false yarn nx run ${name}:start</code></pre>
<p><a href="${escape(`${rootHref}/${project.root}/README.md`)}">README: settings, setup, and how to verify</a></p>
</section>
</div>
</article>`;
}

function sceneFigure(app: string, scene: CatalogueScene): string {
  const { screenshots, text } = scene;
  const label = (display: string, shown: string): string =>
    escape(`${app}, ${scene.title}, ${display}: ${shown || 'blank'}`);
  return `<figure class="scene">
<div class="bar">
<div class="display front" data-label="Front"><img src="${dataUrl(screenshots.front)}" width="72" height="16" alt="${label('front display', text.front)}"></div>
<div class="display back" data-label="Back"><img src="${dataUrl(screenshots.back)}" width="160" height="80" alt="${label('back display', text.back)}"></div>
</div>
<figcaption><b>${escape(scene.title)}</b> ${escape(scene.caption)}</figcaption>
</figure>`;
}

function dataUrl(png: Uint8Array): string {
  return `data:image/png;base64,${Buffer.from(png).toString('base64')}`;
}

const ENTITIES: Readonly<Record<string, string>> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

function escape(text: string): string {
  return text.replaceAll(/[&<>"']/gu, (char) => ENTITIES[char] ?? char);
}
